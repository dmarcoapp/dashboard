export const mockReportsResponse = (page = 1, pageSize = 10): ReportsResponse => {
  const start = (page - 1) * pageSize;
  const end = start + pageSize;
  const items = mockReportsList.slice(start, end);
  
  return {
    items,
    meta: {
      totalCount: mockReportsList.length,
      pageCount: Math.ceil(mockReportsList.length / pageSize),
      filterableFields: ['domain', 'reportingOrganization'],
      sortableFields: ['domain', 'beginDate', 'endDate', 'sumCount'],
    },
  };
};

export const getMockReportById = (id: string): ReportApi => {
  const report = mockReportsList.find(r => r.id === id);
  return report || mockReportsList[0];
};

export const mockRecordsResponse = (reportId: string): RecordsResponse => {
  const records = mockRecords.filter(r => r.reportId === reportId || reportId === 'report-1');
  return {
    items: records.length > 0 ? records : mockRecords,
    meta: {
      totalCount: records.length || mockRecords.length,
      pageCount: 1,
      filterableFields: ['sourceIp', 'disposition'],
      sortableFields: ['sourceIp', 'count'],
    },
  };
};
